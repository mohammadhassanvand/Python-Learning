import random

# وقتی حال انجام کاری رو نداری ولی باید یه بهانه بیاری
# این به کارت میاد

excuses = [
    "سردرد شدید دارم، واقعاً نمی‌تونم.",
    "اینترنت قطع شده، بعداً می‌گم.",
    "مادرم صدازده، باید برم.",
    "دارم روی یه چیز مهم کار می‌کنم، بعداً.",
    "باتری لپتاپم داره تموم می‌شه.",
    "یه کار ضروری پیش اومده، معذرت.",
    "حالم خوب نیست، ببخشید.",
    "فراموش کردم، راستش یادم رفت.",
    "الان توی جلسه‌ام، بعداً پیام می‌دم.",
    "دارم شام درست می‌کنم، بعداً برمی‌گردم.",
    "گوشیم شارژ نداره، قطع می‌شه الان.",
    "یکی زنگ زده، باید جواب بدم."
]

print("=========================")
print("  ژنراتور بهانه‌های آماده")
print("=========================\n")

while True:
    input("اینتر بزن تا یه بهانه بهت بدم... ")
    print("→ " + random.choice(excuses))
    print()
    
    again = input("یکی دیگه؟ (بله/نه): ").strip().lower()
    if again not in ["بله", "آره", "ب", "y", "yes"]:
        print("\nموفق باشی، امیدوارم کسی باورت کنه :)")
        break
