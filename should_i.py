import random

# اینو یه شب دیر وقت نوشتم چون حوصله تصمیم‌گیری نداشتم
# امیدوارم به دردت بخوره

def decide():
    options = [
        "آره، برو انجامش بده",
        "نه، بهتره فعلاً ولش کنی",
        "ممکنه بد نباشه، ولی احتیاط کن",
        "اگر حسش رو داری آره، وگرنه نه",
        "من که می‌گم بکن، بعدش پشیمون نشی ها",
        "اصلاً فکرشم نکن، نه",
        "۵۰-۵۰ هست، سکه بنداز بهتره",
        "آره ولی فردا، نه امشب",
        "نه جدی، نکن",
        "برو دیگه، چی منتظری؟"
    ]
    return random.choice(options)

print("==============================")
print("   ابزار تصمیم‌گیری تنبل‌ها")
print("==============================")
print("هر سوالی که داری بپرس، من برات تصمیم می‌گیرم.\n")

while True:
    q = input("سوالت چیه؟ (یا بنویس خروج): ").strip()
    
    if q.lower() in ["خروج", "exit", "quit", ""]:
        print("\nباشه، موفق باشی.")
        break
    
    if len(q) < 3:
        print("یه سوال درست حسابی بپرس دیگه...\n")
        continue
        
    print("\nفکر می‌کنم...")
    print("→ " + decide())
    print()
